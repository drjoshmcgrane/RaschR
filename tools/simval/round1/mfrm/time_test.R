cat("fit time:", as.numeric(t1-t0, units="secs"), "s\n")
cat("n virtual items:", ncol(mf$X), " n persons:", nrow(mf$X), "\n")
print(cor(mf$facet_effects$rater$severity, attr(d,"truth")$severity))
print(cor(mf$item_effects$location, attr(d,"truth")$difficulty))
